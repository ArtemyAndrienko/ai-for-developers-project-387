-- 0004: профиль Организатора — IANA-часовой пояс (ADR-0004, билет #4 карты).
-- Аддитивная: до появления профиля все Организаторы живут в UTC-дефолте
-- (детерминированном, не в локации процесса). Email — NOCASE, как в прочих
-- таблицах: профиль сопоставляется с встречами без учёта регистра.

CREATE TABLE organizers (
	email TEXT PRIMARY KEY COLLATE NOCASE,
	timezone TEXT NOT NULL
);
